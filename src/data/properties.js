export const formatPrice = (property) => {
  const formatted = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(property.price)

  return property.priceUnit ? `${formatted} / ${property.priceUnit}` : formatted
}

